import fs from "fs";
import path from "path";
import { discoverAssets } from "../src/lib/asset-discovery";

function main() {
  console.log("🎬 BINDU Creative Studio — Generating Media Assets Manifest...");

  const rootDir = process.cwd();
  const manifest = discoverAssets(rootDir);

  const dataDir = path.join(rootDir, "src", "data");
  if (!fs.existsSync(dataDir)) {
    fs.mkdirSync(dataDir, { recursive: true });
  }

  // 1. Write JSON
  const jsonPath = path.join(dataDir, "assets-manifest.json");
  fs.writeFileSync(jsonPath, JSON.stringify(manifest, null, 2), "utf-8");

  // 2. Write TS helper
  const tsPath = path.join(dataDir, "assets-manifest.ts");
  const tsContent = `// Auto-generated by scripts/generate-assets-manifest.ts
// Do not edit manually. Run 'npm run manifest' to regenerate.
import { AssetsManifest } from "../types/media";

export const ASSETS_MANIFEST: AssetsManifest = ${JSON.stringify(manifest, null, 2)};
`;
  fs.writeFileSync(tsPath, tsContent, "utf-8");

  console.log("✨ Assets Manifest Generated Successfully!");
  console.log(`📁 Projects found: ${manifest.projects.length}`);
  manifest.projects.forEach((p) => {
    console.log(`   - [${p.category}] ${p.title} (${p.media.length} media items)`);
  });
  console.log(`🖼️  Gallery Images: ${manifest.gallery.images.length}`);
  console.log(`🎥 Gallery Videos: ${manifest.gallery.videos.length}`);
  console.log(`👤 Profile Image: ${manifest.profileImage ? "Found" : "None (Using Monogram Placeholder)"}`);
  console.log(`💾 Saved to: ${jsonPath} and ${tsPath}\n`);
}

main();
